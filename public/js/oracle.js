// The second orb's controller: picks a model configuration this browser can
// hold, runs it in a worker, and keeps one stream of thoughts going from the
// human comments and its own bounded memory.
//
// The stream belongs to this browser, not the site: the model runs on the
// visitor's own device (the server's 256 MB machine can't hold it beside the
// guestbook), its memory lives in this browser's localStorage, and a Web Lock
// keeps it to one generator across all of this browser's tabs.

import { createLoop } from "./oracle-loop.js";
import {
  LIMITS,
  accept,
  buildPrompt,
  chooseHumans,
  cleanThought,
  compact,
  compactionPrompt,
  emptyMemory,
  isRepetitive,
  needsCompaction,
  sanitise,
  skip,
} from "./oracle-memory.js";

// Everything a different model or budget would change, in one place.
export const CONFIG = {
  model: {
    id: "LiquidAI/LFM2.5-230M-ONNX",
    revision: "c6f46e4e3f885ebcad164d14059a49f90e27eb4d",
    name: "LFM2.5-230M",
    card: "https://huggingface.co/LiquidAI/LFM2.5-230M",
  },
  // Tried in order, each in a fresh worker. WebGPU takes the 4-bit weights;
  // the WebAssembly runtime has no kernel for their quantised embeddings, so
  // it takes the variant with 4-bit layers and 32-bit embeddings instead.
  candidates: [
    { key: "webgpu-q4", device: "webgpu", dtype: "q4", label: "4-bit, on the GPU", mb: 216 },
    { key: "wasm-q4f32", device: "wasm", dtype: "fp32", file: "model_q4f32", label: "4-bit layers, on the CPU", mb: 408, minMemoryGb: 4 },
  ],
  intervalMs: 4000, // rest between completed generations
  generation: { maxNewTokens: LIMITS.maxNewTokens, temperature: 0.8, topP: 0.92, topK: 50, repetitionPenalty: 1.12 },
  summary: { maxNewTokens: LIMITS.summaryTokens, temperature: 0.3, topP: 0.9, topK: 40, repetitionPenalty: 1.1 },
  requestTimeoutMs: 90_000,
  storageKey: "liuru.oracle.v1",
};

const STATUS = {
  asleep: (c) => `Asleep. It runs a small language model (${CONFIG.model.name}) here in your browser; waking it downloads about ${c?.mb ?? 216} MB, once.`,
  loading: (c, p) => `Waking: fetching the model, ${Math.round(p * 100)}% of about ${c.mb} MB.`,
  waiting: () => "Waiting for someone to leave a thought. It only imagines from what people actually wrote.",
  thinking: () => "Imagining…",
  resting: () => "Resting between thoughts.",
  paused: () => "Paused. Its last thoughts stay in the glass.",
  hidden: () => "Resting while this tab is out of sight.",
  elsewhere: () => "Imagining in another tab of yours; its thoughts show here too.",
  retrying: () => "That thought didn't come. Trying again shortly.",
  unavailable: (_c, _p, why) => `It can't run in this browser (${why}). The guestbook works as ever.`,
};

export function createOracle({ root, orb, getTraces, onInspire, onThought }) {
  const status = root.querySelector(".oracle-status");
  const live = root.querySelector(".oracle-phase");
  const toggle = root.querySelector(".oracle-toggle");
  const wakeButton = root.querySelector(".oracle-wake");
  const list = root.querySelector(".oracle-list");
  const summary = root.querySelector(".oracle-summary");
  const engine = root.querySelector(".oracle-engine");

  let memory = load();
  let worker = null;
  let candidate = null;
  let candidates = [];
  let pending = new Map();
  let nextId = 1;
  let phase = "";
  let started = false;
  let loop = null;
  const stats = { kept: 0, rejected: 0, lastMs: 0, inputTokens: 0, outputTokens: 0 };

  // ---------------------------------------------------------------- memory, kept in this browser

  function load() {
    try {
      return sanitise(JSON.parse(localStorage.getItem(CONFIG.storageKey) ?? "null"));
    } catch {
      return emptyMemory();
    }
  }

  function save() {
    try {
      localStorage.setItem(CONFIG.storageKey, JSON.stringify(memory));
    } catch {
      // private mode or a full store: the stream goes on, it just won't survive a reload
    }
  }

  // another tab that owns the stream writes here; this one only shows it
  addEventListener("storage", (e) => {
    if (e.key !== CONFIG.storageKey) return;
    const before = memory.recent.at(-1)?.id;
    memory = load();
    const fresh = memory.recent.at(-1);
    render(fresh && fresh.id !== before ? fresh : null);
  });

  function describe(th) {
    const kinds = th.kinds?.length ? th.kinds.join(", ") : "none recorded";
    return `Generated by ${CONFIG.model.name}${candidate ? ` (${candidate.label})` : ""} in this browser, from anonymous fragments people left here (tagged ${kinds}). Not written by a visitor, and not a summary of any one of them.`;
  }

  function render(fresh = null) {
    orb.setThoughts(memory.recent, fresh);
    list.replaceChildren(
      ...[...memory.recent].reverse().map((th) => {
        const li = document.createElement("li");
        const label = document.createElement("span");
        label.className = "visually-hidden";
        label.textContent = "model thought: ";
        const time = document.createElement("time");
        time.dateTime = new Date(th.at).toISOString();
        time.textContent = `no. ${th.id}`;
        li.append(label, th.text, " ", time);
        return li;
      }),
    );
    if (!memory.recent.length) {
      const li = document.createElement("li");
      li.className = "empty";
      li.textContent = "nothing imagined yet";
      list.append(li);
    }
    summary.textContent = memory.summary ? `Older thoughts, folded into a note it keeps for itself: ${memory.summary}` : "";
  }

  // ---------------------------------------------------------------- status

  function setPhase(name, { progress = 0, why = "" } = {}) {
    status.textContent = STATUS[name](candidate ?? candidates[0], progress, why);
    orb.setState(name === "hidden" ? "paused" : name, { progress });
    root.dataset.phase = name;
    // tell a screen reader when the phase changes, never on every percentage or every thought
    if (name !== phase && !["thinking", "resting", "loading"].includes(name)) live.textContent = status.textContent;
    phase = name;
    toggle.hidden = !["thinking", "resting", "paused", "waiting", "retrying", "hidden"].includes(name);
    wakeButton.hidden = name !== "asleep";
  }

  // ---------------------------------------------------------------- the worker

  function spawn() {
    worker = new Worker("/static/js/oracle-worker.js", { type: "module" });
    worker.onmessage = ({ data }) => {
      const wait = pending.get(data.id ?? "load");
      if (data.type === "progress") setPhase("loading", { progress: data.total ? data.loaded / data.total : 0 });
      else if (wait) {
        pending.delete(data.id ?? "load");
        wait(data);
      }
    };
    // a crashed worker (out of memory, usually) fails whatever it was doing
    worker.onerror = (e) => {
      e.preventDefault();
      for (const [, wait] of pending) wait({ type: "failed", message: e.message || "the model's worker stopped", oom: true });
      pending.clear();
    };
  }

  function kill() {
    worker?.terminate();
    worker = null;
    for (const [, wait] of pending) wait({ type: "failed", message: "released" });
    pending.clear();
  }

  function request(message, key) {
    return new Promise((resolve) => {
      const timer = setTimeout(() => {
        pending.delete(key);
        resolve({ type: "failed", message: "it took too long", timeout: true });
      }, CONFIG.requestTimeoutMs * (key === "load" ? 4 : 1));
      pending.set(key, (data) => {
        clearTimeout(timer);
        resolve(data);
      });
      worker.postMessage(message);
    });
  }

  /** What this browser can hold: a GPU adapter for the 4-bit weights, enough memory for the CPU path. */
  async function probe() {
    let adapter = null;
    try {
      adapter = await navigator.gpu?.requestAdapter();
    } catch {
      adapter = null;
    }
    const gb = navigator.deviceMemory; // Chromium only, and capped at 8; unknown elsewhere
    return CONFIG.candidates.filter((c) => (c.device === "webgpu" ? Boolean(adapter) : !gb || gb >= (c.minMemoryGb ?? 0)));
  }

  /** Loads the first candidate that works, releasing each failure before the next. */
  async function loadModel(from = 0) {
    for (let i = from; i < candidates.length; i++) {
      candidate = candidates[i];
      setPhase("loading", { progress: 0 });
      kill();
      spawn();
      const res = await request({ type: "load", model: CONFIG.model, candidate }, "load");
      if (res.type === "ready") {
        engine.textContent = `${CONFIG.model.name}, ${candidate.label}`;
        console.info(`[oracle] ${CONFIG.model.name} ${candidate.key} ready in ${res.ms} ms`);
        return true;
      }
      console.warn(`[oracle] ${candidate.key} failed to load: ${res.message}`);
    }
    kill();
    candidate = null;
    return false;
  }

  async function generate(prompt, params) {
    const id = nextId++;
    const res = await request({ type: "generate", id, system: prompt.system, user: prompt.user, ...params }, id);
    if (res.type !== "result") {
      const err = new Error(res.message);
      err.oom = res.oom;
      throw err;
    }
    stats.lastMs = res.ms;
    stats.inputTokens = res.inputTokens;
    stats.outputTokens = res.outputTokens;
    return res.text;
  }

  // ---------------------------------------------------------------- one turn of the loop

  let epoch = 0;

  async function think() {
    const traces = getTraces();
    if (!traces.length) {
      setPhase("waiting");
      return { status: "waiting" };
    }
    const mine = epoch;
    try {
      if (needsCompaction(memory)) {
        let note;
        try {
          note = await generate(compactionPrompt(memory), CONFIG.summary);
        } catch (err) {
          if (err.oom) throw err;
          note = undefined; // the deterministic fallback takes over
        }
        if (mine !== epoch) return { status: "stale" };
        memory = compact(memory, note);
        save();
      }
      const humans = chooseHumans(traces, memory);
      const prompt = buildPrompt(memory, humans);
      onInspire(humans);
      const raw = await generate(prompt, CONFIG.generation);
      if (mine !== epoch) return { status: "stale" };
      const text = cleanThought(raw, { truncated: stats.outputTokens >= CONFIG.generation.maxNewTokens });
      if (!text || isRepetitive(text, memory, humans, prompt.mode)) {
        stats.rejected++;
        memory = skip(memory, humans);
        save();
        console.info(`[oracle] set aside: ${JSON.stringify(raw)}`);
        return { status: "resting" };
      }
      memory = accept(memory, text, humans);
      save();
      stats.kept++;
      const thought = memory.recent.at(-1);
      render(thought);
      onThought(thought);
      return { status: "resting" };
    } catch (err) {
      if (err.oom && candidate) {
        // out of memory: release this configuration and fall to the next, keeping every thought so far
        const next = candidates.indexOf(candidate) + 1;
        epoch++;
        if (!(await loadModel(next))) {
          setPhase("unavailable", { why: "not enough memory for the model" });
          loop?.stop();
          return { status: "stale" };
        }
      }
      throw err;
    }
  }

  // ---------------------------------------------------------------- starting, pausing, sharing

  async function begin() {
    if (started) return;
    started = true;
    const mine = ++epoch;
    candidates = await probe();
    if (!candidates.length) {
      setPhase("unavailable", { why: "no WebGPU, and too little memory for the CPU version" });
      return;
    }
    const ok = await loadModel();
    if (mine !== epoch) return; // handed over while it was loading
    if (!ok) {
      setPhase("unavailable", { why: "the model wouldn't load" });
      return;
    }
    loop = createLoop({
      think,
      interval: CONFIG.intervalMs,
      onState(name, detail) {
        if (name === "thinking") setPhase("thinking");
        else if (name === "resting") setPhase("resting");
        else if (name === "waiting") setPhase("waiting");
        else if (name === "retrying") setPhase("retrying");
        else if (name === "failed") setPhase("unavailable", { why: String(detail?.message ?? detail).slice(0, 80) });
        else if (name === "held") setPhase(detail.includes("paused") ? "paused" : "hidden");
      },
    });
    if (sessionStorage.getItem("liuru.oracle.paused") === "1") loop.hold("paused");
    if (document.hidden) loop.hold("hidden");
    loop.start();
  }

  // ---------------------------------------------------------------- one generator per browser

  // Only one tab per browser runs the model; the others show its thoughts as
  // they land in storage. A tab out of sight for HAND_OVER_MS lets the model
  // go (freeing its memory) and the lock with it; only tabs in view queue for it.
  const HAND_OVER_MS = 30_000;
  let woken = false;
  let releaseLock = null;
  let queued = null;
  let handOverTimer = 0;

  function own() {
    begin();
    return new Promise((done) => (releaseLock = done));
  }

  function claim() {
    woken = true;
    if (releaseLock || queued || started) return;
    if (!navigator.locks) return void begin();
    navigator.locks.request("liuru-oracle", { ifAvailable: true }, (lock) => {
      if (lock) return own();
      setPhase("elsewhere");
      if (!document.hidden) queue();
    });
  }

  function queue() {
    if (queued || releaseLock) return;
    queued = new AbortController();
    navigator.locks
      .request("liuru-oracle", { signal: queued.signal }, () => {
        queued = null;
        return own();
      })
      .catch(() => {
        // stopped waiting because this tab went out of sight
      });
  }

  function handOver() {
    if (!releaseLock) return;
    epoch++;
    loop?.stop();
    loop = null;
    kill();
    candidate = null;
    started = false;
    const done = releaseLock;
    releaseLock = null;
    done();
    setPhase("hidden");
  }

  document.addEventListener("visibilitychange", () => {
    if (document.hidden) {
      loop?.hold("hidden");
      queued?.abort();
      queued = null;
      if (releaseLock) handOverTimer = setTimeout(handOver, HAND_OVER_MS);
      return;
    }
    clearTimeout(handOverTimer);
    if (loop) loop.release("hidden");
    else if (woken) claim();
  });

  toggle.addEventListener("click", () => {
    if (!loop) return;
    const pause = !loop.holds.includes("paused");
    if (pause) loop.hold("paused");
    else loop.release("paused");
    sessionStorage.setItem("liuru.oracle.paused", pause ? "1" : "0");
    toggle.setAttribute("aria-pressed", String(pause));
    toggle.querySelector("span").textContent = pause ? "let it imagine again" : "pause its imagining";
    if (pause) setPhase("paused");
  });
  if (sessionStorage.getItem("liuru.oracle.paused") === "1") {
    toggle.setAttribute("aria-pressed", "true");
    toggle.querySelector("span").textContent = "let it imagine again";
  }

  wakeButton.addEventListener("click", () => {
    sessionStorage.setItem("liuru.oracle.woken", "1");
    claim();
  });

  // ---------------------------------------------------------------- when to wake

  render();
  (async () => {
    candidates = await probe();
    setPhase("asleep");
    if (!candidates.length) {
      setPhase("unavailable", { why: "no WebGPU, and too little memory for the CPU version" });
      return;
    }
    let cached = false;
    try {
      const store = await caches.open("transformers-cache");
      cached = (await store.keys()).some((k) => k.url.includes(CONFIG.model.id) && k.url.includes(CONFIG.model.revision));
    } catch {
      cached = false;
    }
    const small = matchMedia("(pointer: coarse)").matches || navigator.connection?.saveData;
    // a phone, or a connection asking to save data, is asked before a few hundred megabytes arrive
    const auto = cached || sessionStorage.getItem("liuru.oracle.woken") === "1" || !small;
    if (!auto) return;
    // the model wakes when the twin orbs come into view, not while the visitor is still writing
    const seen = new IntersectionObserver(
      ([entry]) => {
        if (!entry.isIntersecting) return;
        seen.disconnect();
        claim();
      },
      { rootMargin: "25% 0px" },
    );
    seen.observe(root);
  })();

  return {
    describe,
    /** A new human comment arrived: the next generation can start now rather than wait out its rest. */
    nudge() {
      loop?.nudge();
    },
    get stats() {
      return { ...stats, phase, candidate: candidate?.key, memory: { recent: memory.recent.length, summary: memory.summary.length, gen: memory.gen, compactions: memory.compactions }, loop: loop?.stats };
    },
  };
}
